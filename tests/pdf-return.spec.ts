import { test, expect, request as createRequest, type APIRequestContext } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { hash } from 'bcryptjs';
import { PDFDocument } from 'pdf-lib';
import { PrismaClient } from '../src/generated/prisma/client';
import { PrismaPg } from '@prisma/adapter-pg';
const db = new PrismaClient({ adapter: new PrismaPg({ connectionString: process.env.DATABASE_URL }, { schema: 'escola_test' }) });
const baseURL = 'http://localhost:3001';
const password = 'SenhaDevolucao123!';
const slug = `devolver-pdf-${randomUUID().slice(0, 8)}`;
let admin: APIRequestContext, teacher: APIRequestContext, student: APIRequestContext, outsider: APIRequestContext;
let classId: string, studentId: string, documentId: string, deliveredVersion: number;
const notes = [{ id: randomUUID(), page: 1, type: 'text', x: .1, y: .3, width: .4, height: .05, text: 'Resposta antes da devolução.', fontSize: 14, color: '#244f87' }];
test.describe.configure({ mode: 'serial' });
test.beforeAll(async () => {
  if (new URL(process.env.DATABASE_URL!).searchParams.get('schema') !== 'escola_test') throw new Error('Schema de teste obrigatório.');
  const institution = await db.institution.create({ data: { name: 'Teste devolução PDF', slug } });
  const passwordHash = await hash(password, 12);
  const users = [];
  for (const [username, role] of [['admin', 'ADMIN'], ['professor', 'TEACHER'], ['aluno', 'STUDENT'], ['outro', 'TEACHER']] as const) users.push(await db.user.create({ data: { institutionId: institution.id, username, name: `Teste ${username}`, role, passwordHash, mustChangePassword: false } }));
  studentId = users[2].id;
  const course = await db.course.create({ data: { institutionId: institution.id, name: 'Devolução de apostilas' } });
  const classroom = await db.class.create({ data: { courseId: course.id, teacherId: users[1].id, name: 'Turma devolução' } }); classId = classroom.id;
  await db.enrollment.create({ data: { classId, studentId } });
  const lesson = await db.lesson.create({ data: { classId, title: 'Aula devolução', published: true } });
  [admin, teacher, student, outsider] = await Promise.all(users.map(() => createRequest.newContext({ baseURL })));
  for (const [i, client] of [admin, teacher, student, outsider].entries()) expect((await client.post('/api/login', { data: { institution: slug, username: users[i].username, password } })).status()).toBe(200);
  const pdf = await PDFDocument.create(); pdf.addPage();
  const upload = await teacher.post(`/api/learning/lessons/${lesson.id}/documents`, { multipart: { file: { name: 'apostila-devolucao.pdf', mimeType: 'application/pdf', buffer: Buffer.from(await pdf.save()) } } });
  expect(upload.status()).toBe(201); documentId = (await upload.json()).id;
  const initial = await (await student.get(`/api/learning/documents/${documentId}/work`)).json();
  expect((await student.put(`/api/learning/documents/${documentId}/work`, { data: { version: initial.work.version, annotations: notes } })).status()).toBe(200);
  expect((await student.post(`/api/learning/documents/${documentId}/submit`, { data: { version: initial.work.version + 1 } })).status()).toBe(200);
  expect((await teacher.post(`/api/learning/documents/${documentId}/feedback?student=${studentId}`, { data: { comment: 'Complete sua resposta.', grade: 8 } })).status()).toBe(201);
  deliveredVersion = initial.work.version + 2;
});
test.afterAll(async () => { await Promise.all([admin?.dispose(), teacher?.dispose(), student?.dispose(), outsider?.dispose()]); await db.$disconnect(); });

test('devolução exige gestor autorizado e versão atual da entrega', async () => {
  const path = `/api/learning/documents/${documentId}/reopen?student=${studentId}`;
  expect((await student.post(path, { data: { version: deliveredVersion } })).status()).toBe(403);
  expect((await outsider.post(path, { data: { version: deliveredVersion } })).status()).toBe(404);
  expect((await admin.post(path, { data: { version: deliveredVersion }, headers: { Origin: 'https://externo.example' } })).status()).toBe(403);
  expect((await admin.post(path, { data: { version: deliveredVersion - 1 } })).status()).toBe(409);
  expect((await admin.post(path, { data: {} })).status()).toBe(400);
  const unchanged = await (await student.get(`/api/learning/documents/${documentId}/work`)).json();
  expect(unchanged.readOnly).toBe(true); expect(unchanged.work.annotations).toEqual(notes);
});

test('gestor devolve no acompanhamento, aluno edita e reentrega, professor devolve no trabalho', async ({ browser }) => {
  const context = await browser.newContext({ baseURL, storageState: await admin.storageState() });
  const page = await context.newPage(); await page.goto(`/turmas/${classId}`);
  await page.getByRole('tab', { name: 'Aulas e apostilas', exact: true }).click();
  await page.getByRole('button', { name: 'Acompanhar', exact: true }).click();
  const row = page.getByRole('row').filter({ hasText: 'Teste aluno' });
  await expect(row.getByRole('cell', { name: 'Entregue', exact: true })).toBeVisible();
  page.once('dialog', dialog => dialog.dismiss()); await row.getByRole('button', { name: 'Devolver para ajustes', exact: true }).click();
  await expect(row.getByRole('cell', { name: 'Entregue', exact: true })).toBeVisible();
  page.once('dialog', dialog => dialog.accept()); await row.getByRole('button', { name: 'Devolver para ajustes', exact: true }).click();
  await expect(row.getByRole('cell', { name: 'Em andamento', exact: true })).toBeVisible();
  await expect(row.getByRole('button', { name: 'Devolver para ajustes' })).toHaveCount(0);
  const returned = await (await student.get(`/api/learning/documents/${documentId}/work`)).json();
  expect(returned.readOnly).toBe(false); expect(returned.work.submittedAt).toBeNull();
  expect(returned.work.version).toBe(deliveredVersion + 1); expect(returned.work.annotations).toEqual(notes);
  expect(returned.work.feedback[0].comment).toBe('Complete sua resposta.'); expect(returned.work.feedback[0].grade).toBe(8);
  const workId = returned.work.id;
  expect(await db.auditLog.count({ where: { action: 'pdf-reopened', resourceId: workId } })).toBe(1);
  expect((await admin.post(`/api/learning/documents/${documentId}/reopen?student=${studentId}`, { data: { version: returned.work.version } })).status()).toBe(409);
  const learner = await browser.newContext({ baseURL, storageState: await student.storageState() });
  const learnerPage = await learner.newPage(); await learnerPage.goto(`/apostilas/${documentId}`);
  const answer = learnerPage.getByRole('textbox', { name: 'Resposta na página 1' });
  await expect(answer).toBeEditable(); await answer.fill('Resposta completada após a devolução.');
  await expect(learnerPage.getByRole('status')).toHaveText('Todas as alterações salvas');
  learnerPage.once('dialog', dialog => dialog.accept()); await learnerPage.getByRole('button', { name: 'Entregar apostila', exact: true }).click();
  await expect(learnerPage.getByRole('status')).toHaveText('Apostila entregue');
  expect((await admin.post(`/api/learning/documents/${documentId}/reopen?student=${studentId}`, { data: { version: deliveredVersion } })).status()).toBe(409);
  const instructor = await browser.newContext({ baseURL, storageState: await teacher.storageState(), viewport: { width: 390, height: 844 } });
  const instructorPage = await instructor.newPage(); await instructorPage.goto(`/apostilas/${documentId}?aluno=${studentId}`);
  await expect(instructorPage.getByRole('heading', { name: 'Apostila entregue', exact: true })).toBeVisible();
  await instructorPage.screenshot({ path: 'test-results/devolver-apostila-celular.png', fullPage: true });
  instructorPage.once('dialog', dialog => dialog.accept()); await instructorPage.getByRole('button', { name: 'Devolver para ajustes', exact: true }).click();
  await expect(instructorPage.getByRole('heading', { name: 'Apostila em andamento', exact: true })).toBeVisible();
  const final = await (await student.get(`/api/learning/documents/${documentId}/work`)).json();
  expect(final.readOnly).toBe(false); expect(final.work.annotations[0].text).toBe('Resposta completada após a devolução.');
  expect(final.work.feedback[0].grade).toBe(8);
  await Promise.all([context.close(), learner.close(), instructor.close()]);
});
