  await first.click({ position: { x: 400, y: 350 } }); await expect(page.locator('.pdf-note')).toHaveCount(1);
  await answer.click(); await page.getByLabel('Tamanho da fonte').fill('28');
  await expect(page.getByRole('status')).toHaveText('Todas as alterações salvas');
  let saved = await (await student.get(`/api/learning/documents/${id}/work`)).json();
  expect(saved.work.annotations[0].fontSize).toBe(28);
  const originalBox = await page.locator('.pdf-note').boundingBox();
  const corner = page.getByRole('button', { name: 'Redimensionar resposta', exact: true });
  const cornerBox = (await corner.boundingBox())!;
  await page.mouse.move(cornerBox.x + cornerBox.width / 2, cornerBox.y + cornerBox.height / 2);
  await page.mouse.down(); await page.mouse.move(cornerBox.x + cornerBox.width / 2 + 90, cornerBox.y + cornerBox.height / 2 + 65, { steps: 8 }); await page.mouse.up();
  const resizedBox = (await page.locator('.pdf-note').boundingBox())!;
  expect(resizedBox.width).toBeGreaterThan(originalBox!.width + 60); expect(resizedBox.height).toBeGreaterThan(originalBox!.height + 40);
  await answer.fill('Texto editado depois de ajustar a caixa.\nSegunda linha.');
  await page.getByLabel('Tamanho da fonte').fill('24');
  await expect(page.getByRole('status')).toHaveText('Todas as alterações salvas');
  saved = await (await student.get(`/api/learning/documents/${id}/work`)).json();
  expect(saved.work.annotations[0].manualSize).toBe(true); expect(saved.work.annotations[0].fontSize).toBe(24);
  const manualWidth = saved.work.annotations[0].width, manualHeight = saved.work.annotations[0].height;
  expect((await page.locator('.pdf-note').boundingBox())!.width).toBeCloseTo(resizedBox.width, 0);
  expect((await page.locator('.pdf-note').boundingBox())!.height).toBeCloseTo(resizedBox.height, 0);
  await corner.focus(); await corner.press('Shift+ArrowRight');
  await expect(page.getByRole('status')).toHaveText('Todas as alterações salvas');
