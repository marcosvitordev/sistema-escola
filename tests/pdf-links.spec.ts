  await page.getByRole('button', { name: 'Como usar o editor' }).click();
  await expect(page.locator('#editor-help')).toBeVisible();
  expect((await page.locator('.editor-controls').boundingBox())!.height).toBeLessThanOrEqual(64);
  await page.getByRole('button', { name: 'Fechar ajuda' }).click();
  await expect(page.getByRole('button', { name: 'Ler', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await first.click({ position: { x: 80, y: 150 } }); await first.click({ position: { x: 160, y: 250 } });
  await expect(page.locator('.pdf-note')).toHaveCount(0);
  expect(await page.locator('.pdf-sheet canvas').count()).toBeLessThan(8);
  await page.getByLabel('Tamanho da fonte').fill('20');
  await page.getByRole('button', { name: 'Escrever resposta' }).click();
  await first.click({ position: { x: 80, y: 250 } });
