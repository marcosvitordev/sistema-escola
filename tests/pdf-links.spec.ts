  await expect.poll(async () => {
    const box = await first.boundingBox(); const bar = await page.locator('.editor-controls').boundingBox();
    return box!.y >= bar!.y + bar!.height && box!.y < bar!.y + bar!.height + 80;
  }).toBe(true);
  expect((await first.boundingBox())!.width).toBeLessThanOrEqual(366);
  expect((await page.locator('.editor-controls').boundingBox())!.height).toBeLessThanOrEqual(64);
  await expect(page.getByRole('button', { name: 'Entregar apostila', exact: true })).toBeInViewport();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
