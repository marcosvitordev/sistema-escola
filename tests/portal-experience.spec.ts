test('professor edita os quatro campos, remove data e preserva os vínculos da aula', async ({ browser }) => {
  const lesson = await db.lesson.findFirstOrThrow({ where: { classId, title: 'Editor de textos' }, include: { documents: true, assessments: true, class: { include: { course: true } } } });
  const endpoint = `/api/learning/lessons/${lesson.id}/edit`;
  const fields = { title: 'Editor atualizado', module: 'Produção de textos', description: 'Descrição revisada para a próxima aula.', scheduledAt: '2026-11-23' };
  expect((await student.post(endpoint, { data: fields })).status()).toBe(403);
  expect((await teacher.post(endpoint, { data: fields, headers: { Origin: 'https://externo.example' } })).status()).toBe(403);
  const stranger = await db.user.create({ data: { institutionId: lesson.class.course.institutionId, name: 'Outro professor', username: `outro-${randomUUID()}`, role: 'TEACHER', passwordHash: await hash(password, 12), mustChangePassword: false } });
  const other = await request.newContext({ baseURL });
  await other.post('/api/login', { data: { institution: slug, username: stranger.username, password } });
  expect((await other.post(endpoint, { data: fields })).status()).toBe(404); await other.dispose();
  for (const invalid of [{ ...fields, scheduledAt: '2026-02-30' }, { ...fields, title: ' ' }, { ...fields, module: '' }, { ...fields, classId: 'outra-turma' }, { ...fields, published: false }]) expect((await teacher.post(endpoint, { data: invalid })).status()).toBe(400);
  const context = await browser.newContext({ baseURL, storageState: await teacher.storageState(), viewport: { width: 390, height: 844 } });
  const page = await context.newPage(); await page.goto(`/turmas/${classId}?secao=lessons`);
  const card = page.locator('.lesson-card').filter({ has: page.locator('summary', { hasText: 'Editor de textos' }) });
  await card.locator('summary').click(); await card.getByRole('button', { name: 'Editar aula: Editor de textos', exact: true }).click();
  const form = page.getByRole('form', { name: 'Editar aula', exact: true });
  await expect(form.getByLabel('Título da aula', { exact: true })).toHaveValue('Editor de textos');
  await expect(form.getByLabel('Data prevista', { exact: false })).toHaveValue('2026-11-10');
  await form.getByLabel('Título da aula', { exact: true }).fill('Alteração cancelada');
  await form.getByRole('button', { name: 'Cancelar edição' }).click();
  await expect(card.locator('summary')).toContainText('Editor de textos');
  await card.getByRole('button', { name: 'Editar aula: Editor de textos', exact: true }).click();
  await form.getByLabel('Título da aula', { exact: true }).fill(fields.title);
  await form.getByLabel('Módulo', { exact: true }).fill(fields.module);
  await form.getByLabel('Descrição', { exact: true }).fill(fields.description);
  await form.getByLabel('Data prevista', { exact: false }).fill(fields.scheduledAt);
  await page.screenshot({ path: 'test-results/editar-aula-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await form.getByRole('button', { name: 'Salvar alterações' }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Aula atualizada com sucesso.' })).toBeVisible();
  await page.reload();
  const updatedCard = page.locator('.lesson-card').filter({ has: page.locator('summary', { hasText: fields.title }) });
  await expect(updatedCard.locator('summary')).toContainText('23/11/2026'); await updatedCard.locator('summary').click();
  await expect(updatedCard).toContainText(fields.description); await expect(updatedCard.getByRole('link', { name: 'Abrir apostila' })).toHaveAttribute('href', `/apostilas/${lesson.documents[0].id}`);
  const saved = await db.lesson.findUniqueOrThrow({ where: { id: lesson.id }, include: { documents: true, assessments: true } });
  expect(saved.published).toBe(true); expect(saved.documents.map(item => item.id)).toEqual(lesson.documents.map(item => item.id)); expect(saved.assessments.map(item => item.id)).toEqual(lesson.assessments.map(item => item.id));
  const home = await (await student.get('/api/student/home')).json();
  expect(home.materials.find((item: { id: string }) => item.id === lesson.documents[0].id)).toMatchObject({ lessonTitle: fields.title, scheduledAt: '2026-11-23T17:00:00.000Z' });
  await updatedCard.getByRole('button', { name: `Editar aula: ${fields.title}`, exact: true }).click();
  await form.getByLabel('Data prevista', { exact: false }).fill(''); await form.getByLabel('Descrição', { exact: true }).fill('');
  await form.getByRole('button', { name: 'Salvar alterações' }).click(); await expect(form).toHaveCount(0);
  expect(await db.lesson.findUniqueOrThrow({ where: { id: lesson.id } })).toMatchObject({ scheduledAt: null, description: '' });
  expect(await db.auditLog.count({ where: { action: 'lesson-edited', resourceId: lesson.id } })).toBe(2);
  await context.close();
});

test('excluir aula confirma, protege acesso e apaga apenas os conteúdos vinculados', async ({ browser }) => {
  const lesson = await db.lesson.findFirstOrThrow({ where: { classId, title: { startsWith: 'Editor' } }, include: { documents: true, assessments: true, class: { include: { course: true } } } });
  const remaining = await db.lesson.findFirstOrThrow({ where: { classId, id: { not: lesson.id } }, include: { documents: true, assessments: true } });
  const learner = await db.user.findFirstOrThrow({ where: { institutionId: lesson.class.course.institutionId, username: 'aluno' } });
  const documentId = lesson.documents[0].id, assessmentId = lesson.assessments[0].id;
  const work = await db.pdfWork.create({ data: { documentId, studentId: learner.id, version: 1, submittedAt: new Date(), revisions: { create: { version: 1, annotations: [] } }, feedback: { create: { teacherId: lesson.class.teacherId, comment: 'Resposta conferida', grade: 8 } } } });
  const question = await db.assessmentQuestion.create({ data: { assessmentId, position: 0, type: 'FILE', prompt: 'Envie o arquivo', points: 1 } });
  const attempt = await db.assessmentAttempt.create({ data: { assessmentId, studentId: learner.id, number: 1, submittedAt: new Date(), gradedAt: new Date() } });
  const file = await db.assessmentFile.create({ data: { assessmentId, questionId: question.id, attemptId: attempt.id, name: 'resposta.txt', mimeType: 'text/plain', content: Buffer.from('Resposta do aluno') } });
  const endpoint = `/api/learning/lessons/${lesson.id}`;
  expect((await student.delete(endpoint)).status()).toBe(403);
  expect((await teacher.delete(endpoint, { headers: { Origin: 'https://externo.example' } })).status()).toBe(403);
  const stranger = await db.user.create({ data: { institutionId: lesson.class.course.institutionId, name: 'Professor sem permissão', username: `externo-${randomUUID()}`, role: 'TEACHER', passwordHash: await hash(password, 12), mustChangePassword: false } });
  const other = await request.newContext({ baseURL });
  await other.post('/api/login', { data: { institution: slug, username: stranger.username, password } });
  expect((await other.delete(endpoint)).status()).toBe(404); await other.dispose();
  const context = await browser.newContext({ baseURL, storageState: await teacher.storageState(), viewport: { width: 390, height: 844 } });
  const page = await context.newPage(); await page.goto(`/turmas/${classId}?secao=lessons`);
  const card = page.locator('.lesson-card').filter({ has: page.locator('summary', { hasText: lesson.title }) }); await card.locator('summary').click();
  const remove = card.getByRole('button', { name: `Excluir aula: ${lesson.title}`, exact: true });
  page.once('dialog', dialog => { expect(dialog.message()).toContain('Todas as apostilas, provas, atividades, respostas, entregas e correções'); return dialog.dismiss(); });
  await remove.click(); await expect(remove).toBeVisible(); expect(await db.lesson.count({ where: { id: lesson.id } })).toBe(1);
  page.once('dialog', dialog => dialog.accept()); await remove.click();
  await expect(page.getByRole('status').filter({ hasText: 'Aula excluída com sucesso.' })).toBeVisible(); await expect(card).toHaveCount(0);
  await page.reload(); await expect(page.locator('.lesson-card')).toHaveCount(1);
  expect(await db.lesson.count({ where: { id: lesson.id } })).toBe(0);
  expect(await db.pdfDocument.count({ where: { id: documentId } })).toBe(0);
  expect(await db.pdfWork.count({ where: { id: work.id } })).toBe(0);
  expect(await db.pdfRevision.count({ where: { workId: work.id } })).toBe(0);
  expect(await db.pdfFeedback.count({ where: { workId: work.id } })).toBe(0);
  expect(await db.assessment.count({ where: { id: assessmentId } })).toBe(0);
  expect(await db.assessmentAttempt.count({ where: { id: attempt.id } })).toBe(0);
  expect(await db.assessmentQuestion.count({ where: { id: question.id } })).toBe(0);
  expect(await db.assessmentFile.count({ where: { id: file.id } })).toBe(0);
  expect(await db.auditLog.count({ where: { action: 'lesson-deleted', resourceId: lesson.id } })).toBe(1);
  expect((await teacher.delete(endpoint)).status()).toBe(404);
  expect(await db.lesson.count({ where: { id: remaining.id } })).toBe(1);
  expect(await db.pdfDocument.count({ where: { id: remaining.documents[0].id } })).toBe(1);
  expect(await db.assessment.count({ where: { id: remaining.assessments[0].id } })).toBe(1);
  const home = await (await student.get('/api/student/home')).json();
  expect(home.materials.map((item: { id: string }) => item.id)).toEqual([remaining.documents[0].id]);
  expect(home.assessments.map((item: { id: string }) => item.id)).toEqual([remaining.assessments[0].id]);
  expect((await student.get(`/api/learning/documents/${documentId}/file`)).status()).toBe(404);
  const empty = await teacher.post('/api/learning/lessons', { data: { classId, title: 'Aula vazia para excluir', module: 'Geral' } });
  expect(empty.status()).toBe(201); const emptyId = (await empty.json()).id;
  expect((await teacher.delete(`/api/learning/lessons/${emptyId}`)).status()).toBe(200);
  expect(await db.lesson.count({ where: { id: emptyId } })).toBe(0);
  await context.close();
});
